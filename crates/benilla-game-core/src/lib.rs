fn append_creature_move(
    hostile: &mut HostileState,
    target: WorldPosition,
    stop_distance: f32,
    elapsed_ms: u32,
    updates: &mut Vec<CreatureAiUpdate>,
) {
    if elapsed_ms == 0 || hostile.position.map_id != target.map_id {
        return;
    }
    let start = hostile.position;
    let dx = target.x - start.x;
    let dy = target.y - start.y;
    let distance = dx.hypot(dy);
    let travel = (distance - stop_distance)
        .max(0.0)
        .min(CREATURE_RUN_SPEED_YARDS_PER_SEC * elapsed_ms as f32 / 1_000.0);
    if travel <= 0.0 {
        return;
    }
    let ratio = travel / distance;
    let end = WorldPosition {
        x: start.x + dx * ratio,
        y: start.y + dy * ratio,
        z: start.z + (target.z - start.z) * ratio,
        orientation: dy.atan2(dx),
        ..start
    };
    hostile.spline_id = hostile.spline_id.wrapping_add(1).max(1);
    let duration_ms = (travel / CREATURE_RUN_SPEED_YARDS_PER_SEC * 1_000.0)
        .round()
        .clamp(1.0, elapsed_ms as f32) as u32;
    hostile.position = end;
    updates.push(CreatureAiUpdate::Move {
        spawn_id: hostile.spawn_id,
        start,
        end,
        spline_id: hostile.spline_id,
        duration_ms,
    });
}

fn distance_squared(a: WorldPosition, b: WorldPosition) -> f32 {
    let dx = a.x - b.x;
    let dy = a.y - b.y;
    let dz = a.z - b.z;
    dx * dx + dy * dy + dz * dz
}

fn normalize_name(name: &str) -> Option<String> {
    let mut chars = name.chars();
    let first = chars.next()?;
    let normalized = first
        .to_uppercase()
        .chain(chars.flat_map(char::to_lowercase))
        .collect::<String>();
    let count = normalized.chars().count();
    if !(2..=12).contains(&count) || !normalized.chars().all(char::is_alphabetic) {
        return None;
    }
    Some(normalized)
}

#[derive(Serialize, Deserialize)]
struct CheckedDocument {
    schema_version: u32,
    sha1: String,
    payload: String,
}

fn encode_checked<T: Serialize>(version: u32, value: &T) -> Result<String, SaveError> {
    let payload = toml::to_string(value).map_err(|e| SaveError::InvalidToml(e.to_string()))?;
    let document = CheckedDocument {
        schema_version: version,
        sha1: sha1_hex(payload.as_bytes()),
        payload,
    };
    toml::to_string(&document).map_err(|e| SaveError::InvalidToml(e.to_string()))
}

fn decode_checked<T: DeserializeOwned>(expected: u32, source: &str) -> Result<T, SaveError> {
    let document: CheckedDocument =
        toml::from_str(source).map_err(|e| SaveError::InvalidToml(e.to_string()))?;
    if document.schema_version != expected {
        return Err(SaveError::UnsupportedVersion(document.schema_version));
    }
    if sha1_hex(document.payload.as_bytes()) != document.sha1 {
        return Err(SaveError::ChecksumMismatch);
    }
    toml::from_str(&document.payload).map_err(|e| SaveError::InvalidToml(e.to_string()))
}

pub fn decode_profile(source: &str) -> Result<Profile, SaveError> {
    let profile: Profile = decode_checked(PROFILE_VERSION, source)?;
    if profile.schema_version != PROFILE_VERSION {
        return Err(SaveError::UnsupportedVersion(profile.schema_version));
    }
    Ok(profile)
}

pub fn decode_snapshot(source: &str) -> Result<CharacterSnapshot, SaveError> {
    let document: CheckedDocument =
        toml::from_str(source).map_err(|error| SaveError::InvalidToml(error.to_string()))?;
    if !matches!(
        document.schema_version,
        LEGACY_SNAPSHOT_VERSION
            | PROGRESSION_SNAPSHOT_VERSION
            | QUEST_SNAPSHOT_VERSION
            | POWER_SNAPSHOT_VERSION
            | EQUIPMENT_SNAPSHOT_VERSION
            | PREVIOUS_SNAPSHOT_VERSION
            | BODY_PROPORTIONS_SNAPSHOT_VERSION
            | POOLS_SNAPSHOT_VERSION
            | SNAPSHOT_VERSION
    ) {
        return Err(SaveError::UnsupportedVersion(document.schema_version));
    }
    if sha1_hex(document.payload.as_bytes()) != document.sha1 {
        return Err(SaveError::ChecksumMismatch);
    }
    let snapshot = match document.schema_version {
        LEGACY_SNAPSHOT_VERSION => {
            let legacy: LegacyCharacterSnapshot = toml::from_str(&document.payload)
                .map_err(|error| SaveError::InvalidToml(error.to_string()))?;
            if legacy.schema_version != LEGACY_SNAPSHOT_VERSION {
                return Err(SaveError::InvalidSnapshot);
            }
            let rng_state = initial_rng_state(&legacy.id);
            CharacterSnapshot {
                schema_version: SNAPSHOT_VERSION,
                known_spell_ids: progression::starter_spell_ids(
                    legacy.appearance.race,
                    legacy.appearance.class,
                ),
                money_copper: 0,
                experience: 0,
                inventory: Vec::new(),
                equipment: Vec::new(),
                corpse_loot: Vec::new(),
                quest_journal: quest::QuestJournal::default(),
                health: PLAYER_MAX_HEALTH,
                mana: maximum_mana(legacy.appearance.class),
                rage: 0,
                energy: maximum_energy(legacy.appearance.class),
                focus: 0,
                auras: Vec::new(),
                rng_state,
                id: legacy.id,
                name: legacy.name,
                appearance: legacy.appearance,
                body_proportions: BodyProportions::default(),
                level: legacy.level,
                position: legacy.position,
                play_time_ms: legacy.play_time_ms,
                game_time_minutes: legacy.game_time_minutes,
            }
        }
        PROGRESSION_SNAPSHOT_VERSION => {
            let legacy: ProgressionCharacterSnapshot = toml::from_str(&document.payload)
                .map_err(|error| SaveError::InvalidToml(error.to_string()))?;
            if legacy.schema_version != PROGRESSION_SNAPSHOT_VERSION {
                return Err(SaveError::InvalidSnapshot);
            }
            let rng_state = initial_rng_state(&legacy.id);
            CharacterSnapshot {
                schema_version: SNAPSHOT_VERSION,
                id: legacy.id,
                name: legacy.name,
                appearance: legacy.appearance,
                body_proportions: BodyProportions::default(),
                level: legacy.level,
                known_spell_ids: legacy.known_spell_ids,
                money_copper: legacy.money_copper,
                experience: 0,
                inventory: Vec::new(),
                equipment: Vec::new(),
                corpse_loot: Vec::new(),
                quest_journal: quest::QuestJournal::default(),
                health: PLAYER_MAX_HEALTH,
                mana: maximum_mana(legacy.appearance.class),
                rage: 0,
                energy: maximum_energy(legacy.appearance.class),
                focus: 0,
                auras: Vec::new(),
                rng_state,
                position: legacy.position,
                play_time_ms: legacy.play_time_ms,
                game_time_minutes: legacy.game_time_minutes,
            }
        }
        QUEST_SNAPSHOT_VERSION => {
            let legacy: QuestCharacterSnapshot = toml::from_str(&document.payload)
                .map_err(|error| SaveError::InvalidToml(error.to_string()))?;
            if legacy.schema_version != QUEST_SNAPSHOT_VERSION {
                return Err(SaveError::InvalidSnapshot);
            }
            let rng_state = initial_rng_state(&legacy.id);
            CharacterSnapshot {
                schema_version: SNAPSHOT_VERSION,
                id: legacy.id,
                name: legacy.name,
                appearance: legacy.appearance,
                body_proportions: BodyProportions::default(),
                level: legacy.level,
                known_spell_ids: legacy.known_spell_ids,
                money_copper: legacy.money_copper,
                experience: legacy.experience,
                inventory: legacy.inventory,
                equipment: Vec::new(),
                corpse_loot: Vec::new(),
                quest_journal: legacy.quest_journal,
                health: PLAYER_MAX_HEALTH,
                mana: maximum_mana(legacy.appearance.class),
                rage: 0,
                energy: maximum_energy(legacy.appearance.class),
                focus: 0,
                auras: Vec::new(),
                rng_state,
                position: legacy.position,
                play_time_ms: legacy.play_time_ms,
                game_time_minutes: legacy.game_time_minutes,
            }
        }
        POWER_SNAPSHOT_VERSION => {
            let mut snapshot: CharacterSnapshot = toml::from_str(&document.payload)
                .map_err(|error| SaveError::InvalidToml(error.to_string()))?;
            if snapshot.schema_version != POWER_SNAPSHOT_VERSION {
                return Err(SaveError::InvalidSnapshot);
            }
            snapshot.schema_version = SNAPSHOT_VERSION;
            snapshot.rng_state = initial_rng_state(&snapshot.id);
            snapshot
        }
        EQUIPMENT_SNAPSHOT_VERSION => {
            let mut snapshot: CharacterSnapshot = toml::from_str(&document.payload)
                .map_err(|error| SaveError::InvalidToml(error.to_string()))?;
            if snapshot.schema_version != EQUIPMENT_SNAPSHOT_VERSION {
                return Err(SaveError::InvalidSnapshot);
            }
            snapshot.schema_version = SNAPSHOT_VERSION;
            snapshot.rng_state = initial_rng_state(&snapshot.id);
            snapshot
        }
        PREVIOUS_SNAPSHOT_VERSION => {
            let mut snapshot: CharacterSnapshot = toml::from_str(&document.payload)
                .map_err(|error| SaveError::InvalidToml(error.to_string()))?;
            if snapshot.schema_version != PREVIOUS_SNAPSHOT_VERSION {
                return Err(SaveError::InvalidSnapshot);
            }
            snapshot.schema_version = SNAPSHOT_VERSION;
            snapshot.body_proportions = BodyProportions::default();
            snapshot
        }
        BODY_PROPORTIONS_SNAPSHOT_VERSION => {
            let mut snapshot: CharacterSnapshot = toml::from_str(&document.payload)
                .map_err(|error| SaveError::InvalidToml(error.to_string()))?;
            if snapshot.schema_version != BODY_PROPORTIONS_SNAPSHOT_VERSION {
                return Err(SaveError::InvalidSnapshot);
            }
            snapshot.schema_version = SNAPSHOT_VERSION;
            snapshot.corpse_loot.clear();
            snapshot
        }
        POOLS_SNAPSHOT_VERSION => {
            // Schema 9 adds rage, energy and focus; their serde defaults seed the pools with the
            // pre-pool state (empty rage, no energy or focus for a class that never used one).
            let mut snapshot: CharacterSnapshot = toml::from_str(&document.payload)
                .map_err(|error| SaveError::InvalidToml(error.to_string()))?;
            if snapshot.schema_version != POOLS_SNAPSHOT_VERSION {
                return Err(SaveError::InvalidSnapshot);
            }
            snapshot.schema_version = SNAPSHOT_VERSION;
            snapshot
        }
        SNAPSHOT_VERSION => {
            let snapshot: CharacterSnapshot = toml::from_str(&document.payload)
                .map_err(|error| SaveError::InvalidToml(error.to_string()))?;
            if snapshot.schema_version != SNAPSHOT_VERSION {
                return Err(SaveError::InvalidSnapshot);
            }
            snapshot
        }
        _ => unreachable!("snapshot version was checked above"),
    };
    let mut snapshot = snapshot;
    if document.schema_version < EQUIPMENT_SNAPSHOT_VERSION {
        grant_starting_equipment(&mut snapshot);
    }
    if snapshot.schema_version != SNAPSHOT_VERSION
        || !snapshot.position.is_finite()
        || !snapshot.body_proportions.is_valid()
        || !valid_level_experience(&snapshot)
        || !valid_known_spells(&snapshot.known_spell_ids)
        || !valid_inventory(&snapshot.inventory)
        || !valid_equipment(&snapshot.equipment)
        || !distinct_instance_ids(&snapshot.inventory, &snapshot.equipment)
        || !valid_corpse_loot(&snapshot.corpse_loot)
        || !quest::valid_journal(&snapshot.quest_journal)
        || !valid_vitals(&snapshot)
        || normalize_name(&snapshot.name).as_deref() != Some(snapshot.name.as_str())
    {
        return Err(SaveError::InvalidSnapshot);
    }
    Ok(snapshot)
}

fn sha1_hex(bytes: &[u8]) -> String {
    use sha1::Digest;
    sha1::Sha1::digest(bytes)
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect()
}

