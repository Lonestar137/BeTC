    pub fn create_character(
        &mut self,
        id: CharacterId,
        name: &str,
        appearance: Appearance,
        start: WorldPosition,
    ) -> Result<CharacterId, CoreError> {
        if self.profile.characters.len() >= MAX_CHARACTERS {
            return Err(CoreError::RosterFull);
        }
        if self.snapshots.contains_key(&id)
            || self
                .snapshots
                .keys()
                .any(|existing| existing.presentation_guid() == id.presentation_guid())
        {
            return Err(CoreError::InvalidCharacterId);
        }
        if !start.is_finite() {
            return Err(CoreError::InvalidPosition);
        }
        let name = normalize_name(name).ok_or(CoreError::InvalidName)?;
        if self
            .profile
            .characters
            .iter()
            .any(|entry| entry.name.eq_ignore_ascii_case(&name))
        {
            return Err(CoreError::DuplicateName);
        }
        self.profile.characters.push(RosterEntry {
            id: id.clone(),
            name: name.clone(),
        });
        self.snapshots.insert(id.clone(), {
            let mut snapshot = CharacterSnapshot {
                schema_version: SNAPSHOT_VERSION,
                id: id.clone(),
                name,
                appearance,
                body_proportions: BodyProportions::default(),
                level: 1,
                known_spell_ids: progression::starter_spell_ids(appearance.race, appearance.class),
                money_copper: 0,
                experience: 0,
                inventory: Vec::new(),
                equipment: Vec::new(),
                corpse_loot: Vec::new(),
                quest_journal: quest::QuestJournal::default(),
                health: PLAYER_MAX_HEALTH,
                mana: maximum_mana(appearance.class),
                rage: 0,
                energy: maximum_energy(appearance.class),
                focus: 0,
                auras: Vec::new(),
                rng_state: initial_rng_state(&id),
                position: start,
                play_time_ms: 0,
                game_time_minutes: INITIAL_GAME_TIME_MINUTES,
            };
            grant_starting_equipment(&mut snapshot);
            snapshot
        });
        self.profile.selected.get_or_insert_with(|| id.clone());
        Ok(id)
    }

    /// Set a character's cosmetic model proportions while it is not active in the world.
    pub fn set_body_proportions(
        &mut self,
        id: &CharacterId,
        proportions: BodyProportions,
    ) -> Result<(), CoreError> {
        if self.active.is_some() {
            return Err(CoreError::CharacterActive);
        }
        if !proportions.is_valid() {
            return Err(CoreError::InvalidAppearance);
        }
        let snapshot = self
            .snapshots
            .get_mut(id)
            .ok_or(CoreError::CharacterNotFound)?;
        snapshot.body_proportions = proportions;
        Ok(())
    }

    pub fn delete_character(&mut self, id: &CharacterId) -> Result<(), CoreError> {
        if self.active.as_ref() == Some(id) {
            return Err(CoreError::CharacterActive);
        }
        let old_len = self.profile.characters.len();
        self.profile.characters.retain(|entry| &entry.id != id);
        if old_len == self.profile.characters.len() {
            return Err(CoreError::CharacterNotFound);
        }
        self.snapshots.remove(id);
        if self.profile.selected.as_ref() == Some(id) {
            self.profile.selected = self
                .profile
                .characters
                .first()
                .map(|entry| entry.id.clone());
        }
        Ok(())
    }

    pub fn select_character(&mut self, id: &CharacterId) -> Result<(), CoreError> {
        if self.active.is_some() {
            return Err(CoreError::CharacterActive);
        }
        if !self.snapshots.contains_key(id) {
            return Err(CoreError::CharacterNotFound);
        }
        self.profile.selected = Some(id.clone());
        Ok(())
    }

    pub fn enter_world(&mut self) -> Result<CharacterSnapshot, CoreError> {
        if self.active.is_some() {
            return Err(CoreError::CharacterActive);
        }
        let id = self
            .profile
            .selected
            .as_ref()
            .ok_or(CoreError::NoCharacterSelected)?;
        let snapshot = self
            .snapshots
            .get(id)
            .ok_or(CoreError::CharacterNotFound)?
            .clone();
        self.active = Some(id.clone());
        self.minute_remainder_ms = 0;
        self.hostiles = Vec::new();
        self.allies = Vec::new();
        self.populate_near(snapshot.position, CONTENT_RADIUS_YARDS);
        self.cast_remaining_ms = 0;
        self.cooldown_remaining_ms = 0;
        self.spell_cooldowns.clear();
        self.cast_target_spawn_id = None;
        self.cast_ally_spawn_id = None;
        self.cast_damage = 0;
        self.cast_spell_id = 0;
        self.cast_is_heal = false;
        self.cast_school = 0;
        self.cast_periodic = None;
        self.cast_channel = None;
        self.cast_control = None;
        self.cast_summon = None;
        self.cast_totem = None;
        self.cast_aura_ms = None;
        self.active_channel = None;
        self.summon = None;
        self.totems.clear();
        self.melee_target_spawn_id = None;
        self.melee_remaining_ms = 0;
        self.mana_regen_remainder_ms = 0;
        self.energy_regen_remainder_ms = 0;
        self.health_regen_remainder_ms = 0;
        self.rage_decay_remainder_ms = 0;
        self.ranged_target_spawn_id = None;
        self.ranged_remaining_ms = 0;
        self.ranged_spell_id = 0;
        self.queued_melee = None;
        self.combo_points = 0;
        self.combo_target_spawn_id = None;
        self.cast_combo = ComboEffect::None;
        self.active_health = snapshot.health;
        self.active_mana = snapshot.mana;
        self.active_rage = snapshot.rage;
        self.active_energy = snapshot.energy;
        self.active_focus = snapshot.focus;
        self.open_loot_spawn_id = None;
        for corpse in &snapshot.corpse_loot {
            if let Some(hostile) = self
                .hostiles
                .iter_mut()
                .find(|hostile| hostile.spawn_id == corpse.spawn_id)
            {
                hostile.health = 0;
                hostile.respawn_remaining_ms = Some(corpse.respawn_remaining_ms);
            }
        }
        Ok(snapshot)
    }

