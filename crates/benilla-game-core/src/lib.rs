/// Optional, cosmetic player-model proportions. Values are signed percentage points from the
/// stock shape; hard limits keep the M2 silhouette within an authored-looking range.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
#[serde(default)]
pub struct BodyProportions {
    pub enabled: bool,
    /// -10% to +35%; the top end supports notably tall fantasy characters.
    pub height: i8,
    pub shoulders: i8,
    pub arms: i8,
    pub waist: i8,
    pub hips: i8,
    pub bust: i8,
    pub seat: i8,
}

impl BodyProportions {
    pub const HEIGHT_RANGE: std::ops::RangeInclusive<i8> = -10..=35;
    pub const SHAPE_RANGE: std::ops::RangeInclusive<i8> = -20..=20;
    pub const SEAT_RANGE: std::ops::RangeInclusive<i8> = -20..=40;

    pub fn is_valid(self) -> bool {
        Self::HEIGHT_RANGE.contains(&self.height)
            && [self.shoulders, self.arms, self.waist, self.hips, self.bust]
                .into_iter()
                .all(|value| Self::SHAPE_RANGE.contains(&value))
            && Self::SEAT_RANGE.contains(&self.seat)
    }

    pub fn height_scale(self) -> f32 {
        1.0 + f32::from(
            self.height
                .clamp(*Self::HEIGHT_RANGE.start(), *Self::HEIGHT_RANGE.end()),
        ) / 100.0
    }
}

/// A converted unit's reaction toward the active character, the three arms of the client's
/// `FactionTemplate.dbc` comparator (`0x606640`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum UnitReaction {
    /// The unit is hostile: attackable and aggressive.
    Hostile,
    /// Attackable but not aggressive (critters, non-aggro starters).
    Neutral,
    /// Not attackable: friendly NPCs and summons.
    Friendly,
}

/// Population reactions for the active character's race, keyed by the unit's
/// `UNIT_FIELD_FACTIONTEMPLATE`. The adapter builds this from build-8606 `FactionTemplate.dbc`
/// (unit toward the race's player template); a faction with no row reads friendly. `game-core`
/// stays free of client-format dependencies by receiving the converted table.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct UnitReactions {
    by_faction: std::collections::BTreeMap<u32, UnitReaction>,
}

impl UnitReactions {
    pub fn from_pairs(pairs: impl IntoIterator<Item = (u32, UnitReaction)>) -> Self {
        Self {
            by_faction: pairs.into_iter().collect(),
        }
    }

    pub fn reaction(&self, faction_template: u32) -> UnitReaction {
        self.by_faction
            .get(&faction_template)
            .copied()
            .unwrap_or(UnitReaction::Friendly)
    }

    pub fn is_empty(&self) -> bool {
        self.by_faction.is_empty()
    }
}

