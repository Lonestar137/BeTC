    /// Buy a wrapper-aware trainer service, replacing an older known rank when necessary.
    pub fn buy_trainer_spell_with_ranks(
        &mut self,
        trainer_entry: u32,
        spell_id: u32,
        resolve_learned_spell: impl Fn(u32) -> u32 + Copy,
        rank_successor: impl Fn(u32) -> Option<u32> + Copy,
    ) -> Result<TrainerPurchase, progression::TrainerError> {
        let id = self
            .active
            .as_ref()
            .ok_or(progression::TrainerError::NoActiveCharacter)?
            .clone();
        let snapshot = self
            .snapshots
            .get_mut(&id)
            .ok_or(progression::TrainerError::NoActiveCharacter)?;
        let matching_spell: Vec<_> = progression::trainer_offers(trainer_entry)
            .filter(|offer| offer.spell_id == spell_id)
            .collect();
        if matching_spell.is_empty() {
            return Err(progression::TrainerError::TrainerUnavailable);
        }
        let Some(offer) = matching_spell
            .into_iter()
            .find(|offer| offer.class == snapshot.appearance.class)
        else {
            return Err(progression::TrainerError::WrongClass);
        };
        let learned_spell_id = resolve_learned_spell(spell_id);
        if is_spell_known(
            snapshot,
            learned_spell_id,
            resolve_learned_spell,
            rank_successor,
        ) {
            return Err(progression::TrainerError::AlreadyKnown);
        }
        match trainer_condition_satisfied(
            snapshot,
            offer.condition_id,
            resolve_learned_spell,
            rank_successor,
        ) {
            Some(true) => {}
            Some(false) => return Err(progression::TrainerError::ConditionNotMet),
            None => return Err(progression::TrainerError::UnsupportedCondition),
        }
        if offer.required_skill_id != 0 || offer.required_skill_value != 0 {
            return Err(progression::TrainerError::UnsupportedSkill);
        }
        if snapshot.level < offer.required_level {
            return Err(progression::TrainerError::LevelTooLow);
        }
        if offer
            .prerequisite_spell_ids
            .iter()
            .any(|spell| !is_spell_known(snapshot, *spell, resolve_learned_spell, rank_successor))
        {
            return Err(progression::TrainerError::MissingPrerequisite);
        }
        if snapshot.money_copper < offer.cost_copper {
            return Err(progression::TrainerError::InsufficientFunds);
        }

        snapshot.money_copper -= offer.cost_copper;
        let removed_spell_ids: Vec<_> = snapshot
            .known_spell_ids
            .iter()
            .copied()
            .filter(|known| is_lower_rank(*known, learned_spell_id, rank_successor))
            .collect();
        snapshot
            .known_spell_ids
            .retain(|known| !removed_spell_ids.contains(known));
        snapshot.known_spell_ids.push(learned_spell_id);
        snapshot.known_spell_ids.sort_unstable();
        Ok(TrainerPurchase {
            spell_id,
            learned_spell_id,
            removed_spell_ids,
            cost_copper: offer.cost_copper,
            remaining_copper: snapshot.money_copper,
        })
    }

    /// Learn a talent rank after the adapter resolves the client talent row to its source rules.
    pub fn learn_talent(
        &mut self,
        rules: TalentGrantRules<'_>,
    ) -> Result<TalentPurchase, TalentError> {
        let id = self
            .active
            .as_ref()
            .ok_or(TalentError::NoActiveCharacter)?
            .clone();
        let snapshot = self
            .snapshots
            .get_mut(&id)
            .ok_or(TalentError::NoActiveCharacter)?;
        let race = snapshot.appearance.race;
        let class = snapshot.appearance.class;
        if !(1..=32).contains(&race)
            || !(1..=32).contains(&class)
            || rules.race_mask & (1u32 << (race - 1)) == 0
            || rules.class_mask & (1u32 << (class - 1)) == 0
        {
            return Err(TalentError::WrongRaceOrClass);
        }
        if snapshot.level < 10 {
            return Err(TalentError::LevelTooLow);
        }
        let rank = rules
            .rank_spell_ids
            .iter()
            .take_while(|spell| snapshot.known_spell_ids.contains(spell))
            .count() as u32;
        if rank != rules.rank || rank as usize >= rules.rank_spell_ids.len() {
            return Err(TalentError::WrongRank);
        }
        if rules.required_spell_id != 0
            && !snapshot.known_spell_ids.contains(&rules.required_spell_id)
        {
            return Err(TalentError::MissingPrerequisite);
        }
        if rules.prerequisite_spell_id != 0
            && !snapshot
                .known_spell_ids
                .contains(&rules.prerequisite_spell_id)
        {
            return Err(TalentError::MissingPrerequisite);
        }
        let spent_in_class = rules
            .class_spell_ids
            .iter()
            .filter(|spell| snapshot.known_spell_ids.contains(spell))
            .count() as u32;
        let earned = u32::from(snapshot.level.saturating_sub(9));
        if spent_in_class >= earned {
            return Err(TalentError::NoPoints);
        }
        let spent_in_tree = rules
            .tree_spell_ids
            .iter()
            .filter(|spell| snapshot.known_spell_ids.contains(spell))
            .count() as u32;
        if spent_in_tree < rules.tier.saturating_mul(5) {
            return Err(TalentError::TierLocked);
        }

        let mut learned_spell_ids = Vec::new();
        for &spell_id in &rules.rank_spell_ids[..=rank as usize] {
            if !snapshot.known_spell_ids.contains(&spell_id) {
                snapshot.known_spell_ids.push(spell_id);
                learned_spell_ids.push(spell_id);
            }
        }
        snapshot.known_spell_ids.sort_unstable();
        Ok(TalentPurchase {
            learned_spell_ids,
            remaining_points: earned - spent_in_class - 1,
        })
    }

