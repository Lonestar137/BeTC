/// Stable lowercase hexadecimal identity generated by the host and persisted independently of a
/// character's display name.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(try_from = "String", into = "String")]
pub struct CharacterId(String);

impl CharacterId {
    pub fn parse(value: impl Into<String>) -> Result<Self, CoreError> {
        let value = value.into();
        if value.len() != 32 || !value.bytes().all(|b| b.is_ascii_hexdigit()) {
            return Err(CoreError::InvalidCharacterId);
        }
        Ok(Self(value.to_ascii_lowercase()))
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }

    /// Stable `HIGHGUID_PLAYER` presentation guid for the inherited roster's guid-shaped key.
    pub fn presentation_guid(&self) -> u64 {
        (u64::from_str_radix(&self.0[16..], 16).expect("validated character ID is hexadecimal")
            & 0x0000_ffff_ffff_ffff)
            .max(1)
    }
}

impl TryFrom<String> for CharacterId {
    type Error = String;

    fn try_from(value: String) -> Result<Self, Self::Error> {
        Self::parse(value).map_err(|error| error.to_string())
    }
}

impl From<CharacterId> for String {
    fn from(id: CharacterId) -> Self {
        id.0
    }
}

