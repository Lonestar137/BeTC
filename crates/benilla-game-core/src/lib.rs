fn trainer_offer_state(
    snapshot: &CharacterSnapshot,
    offer: &progression::TrainerSpell,
    learned_spell_id: u32,
    resolve_learned_spell: impl Fn(u32) -> u32 + Copy,
    rank_successor: impl Fn(u32) -> Option<u32> + Copy,
) -> TrainerServiceState {
    if is_spell_known(
        snapshot,
        learned_spell_id,
        resolve_learned_spell,
        rank_successor,
    ) {
        return TrainerServiceState::Known;
    }
    let condition = trainer_condition_satisfied(
        snapshot,
        offer.condition_id,
        resolve_learned_spell,
        rank_successor,
    );
    let unavailable = if condition == Some(false) {
        Some(progression::TrainerError::ConditionNotMet)
    } else if condition.is_none() {
        Some(progression::TrainerError::UnsupportedCondition)
    } else if offer.required_skill_id != 0 || offer.required_skill_value != 0 {
        Some(progression::TrainerError::UnsupportedSkill)
    } else if snapshot.level < offer.required_level {
        Some(progression::TrainerError::LevelTooLow)
    } else if offer
        .prerequisite_spell_ids
        .iter()
        .any(|spell| !is_spell_known(snapshot, *spell, resolve_learned_spell, rank_successor))
    {
        Some(progression::TrainerError::MissingPrerequisite)
    } else if snapshot.money_copper < offer.cost_copper {
        Some(progression::TrainerError::InsufficientFunds)
    } else {
        None
    };
    unavailable.map_or(
        TrainerServiceState::Learnable,
        TrainerServiceState::Unavailable,
    )
}

fn is_spell_known(
    snapshot: &CharacterSnapshot,
    spell_id: u32,
    resolve_learned_spell: impl Fn(u32) -> u32,
    rank_successor: impl Fn(u32) -> Option<u32>,
) -> bool {
    let mut required = resolve_learned_spell(spell_id);
    for _ in 0..64 {
        if snapshot.known_spell_ids.contains(&required)
            || snapshot
                .known_spell_ids
                .iter()
                .any(|known| resolve_learned_spell(*known) == required)
        {
            return true;
        }
        let Some(next) = rank_successor(required).filter(|&next| next != required) else {
            return false;
        };
        required = resolve_learned_spell(next);
    }
    false
}

fn trainer_condition_satisfied(
    snapshot: &CharacterSnapshot,
    condition_id: u32,
    resolve_learned_spell: impl Fn(u32) -> u32 + Copy,
    rank_successor: impl Fn(u32) -> Option<u32> + Copy,
) -> Option<bool> {
    fn evaluate(
        snapshot: &CharacterSnapshot,
        condition_id: u32,
        resolve_learned_spell: impl Fn(u32) -> u32 + Copy,
        rank_successor: impl Fn(u32) -> Option<u32> + Copy,
        visiting: &mut Vec<u32>,
    ) -> Option<bool> {
        if condition_id == 0 {
            return Some(true);
        }
        if visiting.len() >= 32 || visiting.contains(&condition_id) {
            return None;
        }
        let condition = progression::spell_condition(condition_id)?;
        if condition.flags != 0 {
            return None;
        }
        visiting.push(condition_id);
        let value = match condition.kind {
            6 => {
                match snapshot.appearance.race {
                    1 | 3 | 4 | 7 | 11 => Some(condition.value1 == 469),
                    2 | 5 | 6 | 8 | 10 => Some(condition.value1 == 67),
                    _ => None,
                }
            }
            14 => {
                let race = snapshot.appearance.race;
                if !(1..=32).contains(&race) {
                    None
                } else {
                    Some(condition.value1 & (1u32 << (race - 1)) != 0)
                }
            }
            17 => Some(is_spell_known(
                snapshot,
                condition.value1,
                resolve_learned_spell,
                rank_successor,
            )),
            -1 | -2 => {
                let child_ids = [
                    condition.value1,
                    condition.value2,
                    condition.value3,
                    condition.value4,
                ];
                let children: Option<Vec<bool>> = child_ids
                    .into_iter()
                    .filter(|&id| id != 0)
                    .map(|id| {
                        evaluate(
                            snapshot,
                            id,
                            resolve_learned_spell,
                            rank_successor,
                            visiting,
                        )
                    })
                    .collect();
                children.and_then(|children| {
                    (!children.is_empty()).then(|| {
                        if condition.kind == -1 {
                            children.into_iter().all(|matched| matched)
                        } else {
                            children.into_iter().any(|matched| matched)
                        }
                    })
                })
            }
            _ => None,
        };
        visiting.pop();
        value
    }

    evaluate(
        snapshot,
        condition_id,
        resolve_learned_spell,
        rank_successor,
        &mut Vec::new(),
    )
}

fn is_lower_rank(
    known_spell_id: u32,
    learned_spell_id: u32,
    rank_successor: impl Fn(u32) -> Option<u32>,
) -> bool {
    let mut rank = known_spell_id;
    for _ in 0..64 {
        let Some(next) = rank_successor(rank).filter(|&next| next != rank) else {
            return false;
        };
        if next == learned_spell_id {
            return true;
        }
        rank = next;
    }
    false
}

fn valid_known_spells(spell_ids: &[u32]) -> bool {
    spell_ids.iter().all(|&spell| spell != 0) && spell_ids.windows(2).all(|pair| pair[0] < pair[1])
}

fn valid_inventory(items: &[quest::InventoryItem]) -> bool {
    items.len() <= usize::from(quest::BACKPACK_SLOTS)
        && items.iter().all(|item| {
            item.instance_id != 0
                && item.instance_id <= u64::from(u16::MAX)
                && item.entry != 0
                && item.count != 0
                && item.slot < quest::BACKPACK_SLOTS
        })
        && items.windows(2).all(|pair| pair[0].slot < pair[1].slot)
        && items.iter().enumerate().all(|(index, item)| {
            !items[index + 1..]
                .iter()
                .any(|later| later.instance_id == item.instance_id)
        })
}

fn valid_equipment(items: &[quest::InventoryItem]) -> bool {
    items.len() <= usize::from(quest::EQUIPMENT_SLOTS)
        && items.iter().all(|item| {
            item.instance_id != 0
                && item.instance_id <= u64::from(u16::MAX)
                && item.entry != 0
                && item.count != 0
                && item.slot < quest::EQUIPMENT_SLOTS
        })
        && items.windows(2).all(|pair| pair[0].slot < pair[1].slot)
}

/// Item instance ids are unique across the whole character, backpack and equipment alike; the
/// presentation adapter derives each item's GUID from the id.
fn distinct_instance_ids(
    inventory: &[quest::InventoryItem],
    equipment: &[quest::InventoryItem],
) -> bool {
    equipment
        .iter()
        .all(|item| inventory.iter().all(|other| other.instance_id != item.instance_id))
        && equipment.iter().enumerate().all(|(index, item)| {
            !equipment[index + 1..]
                .iter()
                .any(|later| later.instance_id == item.instance_id)
        })
}

/// The first free item instance id across the backpack and equipment, 1-based.
fn next_instance_id(snapshot: &CharacterSnapshot) -> Option<u64> {
    (1..=u64::from(u16::MAX)).find(|candidate| {
        snapshot
            .inventory
            .iter()
            .all(|item| item.instance_id != *candidate)
            && snapshot
                .equipment
                .iter()
                .all(|item| item.instance_id != *candidate)
    })
}

/// Wear the TBC starting outfit for the snapshot's race, class and gender. Called at character
/// creation and when an older save (schema < 5) migrates; a slot already worn is left alone.
fn grant_starting_equipment(snapshot: &mut CharacterSnapshot) {
    let (race, class, gender) = (
        snapshot.appearance.race,
        snapshot.appearance.class,
        snapshot.appearance.gender,
    );
    let mut pending: Vec<(u8, u32, u32)> = Vec::new();
    for item in quest::starting_items(race, class, gender) {
        if item.slot >= quest::EQUIPMENT_SLOTS
            || quest::item_template(item.entry).is_none()
            || snapshot.equipment.iter().any(|worn| worn.slot == item.slot)
            || pending.iter().any(|(slot, _, _)| *slot == item.slot)
        {
            continue;
        }
        pending.push((item.slot, item.entry, item.amount.max(1)));
    }
    for (slot, entry, count) in pending {
        let Some(instance_id) = next_instance_id(snapshot) else {
            break;
        };
        snapshot.equipment.push(quest::InventoryItem {
            instance_id,
            entry,
            count,
            slot,
        });
    }
    snapshot.equipment.sort_by_key(|item| item.slot);
}

/// The equipment slots an item entry may occupy, from its `InventoryType`; `None` is a
/// non-equippable entry. Finger and trinket accept either of their pair.
fn allowed_equip_slots(entry: u32) -> Option<Vec<u8>> {
    let template = quest::item_template(entry)?;
    Some(match template.inventory_type {
        1 => vec![0],
        2 => vec![1],
        3 => vec![2],
        4 => vec![3],
        5 | 20 => vec![4],
        6 => vec![5],
        7 => vec![6],
        8 => vec![7],
        9 => vec![8],
        10 => vec![9],
        11 => vec![10, 11],
        12 => vec![12, 13],
        13 | 17 | 21 => vec![15],
        14 | 22 | 23 => vec![16],
        15 | 25 | 26 | 28 => vec![17],
        16 => vec![14],
        19 => vec![18],
        _ => return None,
    })
}

fn take_item(snapshot: &mut CharacterSnapshot, at: ItemSlot) -> Option<quest::InventoryItem> {
    match at {
        ItemSlot::Backpack(slot) => {
            let index = snapshot.inventory.iter().position(|item| item.slot == slot)?;
            Some(snapshot.inventory.remove(index))
        }
        ItemSlot::Equipment(slot) => {
            let index = snapshot.equipment.iter().position(|item| item.slot == slot)?;
            Some(snapshot.equipment.remove(index))
        }
    }
}

fn put_item(snapshot: &mut CharacterSnapshot, at: ItemSlot, mut item: quest::InventoryItem) {
    match at {
        ItemSlot::Backpack(slot) => {
            item.slot = slot;
            snapshot.inventory.push(item);
            snapshot.inventory.sort_by_key(|item| item.slot);
        }
        ItemSlot::Equipment(slot) => {
            item.slot = slot;
            snapshot.equipment.push(item);
            snapshot.equipment.sort_by_key(|item| item.slot);
        }
    }
}

/// Whether a slot index is in range for its container.
fn item_slot_in_range(at: ItemSlot) -> bool {
    match at {
        ItemSlot::Backpack(slot) => slot < quest::BACKPACK_SLOTS,
        ItemSlot::Equipment(slot) => slot < quest::EQUIPMENT_SLOTS,
    }
}

/// Move (or swap) an item between backpack and equipment, honouring the destination's
/// `InventoryType` fit. A swap is two moves in one: any displaced item lands where the source was.
fn move_item_in(
    snapshot: &mut CharacterSnapshot,
    from: ItemSlot,
    to: ItemSlot,
) -> Result<(), CoreError> {
    if from == to {
        return Ok(());
    }
    if !item_slot_in_range(from) || !item_slot_in_range(to) {
        return Err(CoreError::UnknownItem);
    }
    let item = take_item(snapshot, from).ok_or(CoreError::UnknownItem)?;
    if let ItemSlot::Equipment(slot) = to {
        if !allowed_equip_slots(item.entry).is_some_and(|slots| slots.contains(&slot)) {
            put_item(snapshot, from, item);
            return Err(CoreError::WrongEquipSlot);
        }
    }
    if let Some(displaced) = take_item(snapshot, to) {
        if let ItemSlot::Equipment(slot) = from {
            if !allowed_equip_slots(displaced.entry).is_some_and(|slots| slots.contains(&slot)) {
                put_item(snapshot, to, displaced);
                put_item(snapshot, from, item);
                return Err(CoreError::WrongEquipSlot);
            }
        }
        put_item(snapshot, from, displaced);
    }
    put_item(snapshot, to, item);
    Ok(())
}

fn maximum_mana(class: u8) -> u32 {
    matches!(class, 2 | 3 | 5 | 7 | 8 | 9 | 11)
        .then_some(PLAYER_MAX_MANA)
        .unwrap_or(0)
}

fn apply_experience(mut level: u8, mut experience: u32) -> (u8, u32) {
    while level < MAX_PLAYER_LEVEL {
        let Some(required) = progression::xp_to_next_level(level) else {
            break;
        };
        if experience < required {
            break;
        }
        experience -= required;
        level += 1;
    }
    if level == MAX_PLAYER_LEVEL {
        experience = 0;
    }
    (level, experience)
}

fn initial_rng_state(id: &CharacterId) -> u64 {
    (id.as_str()
        .bytes()
        .fold(0xcbf2_9ce4_8422_2325, |state, byte| {
            (state ^ u64::from(byte)).wrapping_mul(0x0000_0100_0000_01b3)
        })
        & i64::MAX as u64)
        .max(1)
}

fn next_random(snapshot: &mut CharacterSnapshot) -> u64 {
    let mut state = snapshot.rng_state;
    state ^= state >> 12;
    state ^= state << 25;
    state ^= state >> 27;
    state &= i64::MAX as u64;
    if state == 0 {
        state = 1;
    }
    snapshot.rng_state = state;
    state.wrapping_mul(0x2545_f491_4f6c_dd1d)
}

fn roll_inclusive(snapshot: &mut CharacterSnapshot, min: u32, max: u32) -> u32 {
    if min == max {
        return min;
    }
    let width = u64::from(max - min) + 1;
    min + (next_random(snapshot) % width) as u32
}

fn valid_vitals(snapshot: &CharacterSnapshot) -> bool {
    snapshot.health <= PLAYER_MAX_HEALTH
        && snapshot.mana <= maximum_mana(snapshot.appearance.class)
        && snapshot.rng_state != 0
        && valid_auras(&snapshot.auras)
}

fn valid_level_experience(snapshot: &CharacterSnapshot) -> bool {
    snapshot.level > 0
        && snapshot.level <= MAX_PLAYER_LEVEL
        && match progression::xp_to_next_level(snapshot.level) {
            Some(required) => snapshot.experience < required,
            None => snapshot.experience == 0,
        }
}

fn valid_auras(auras: &[CharacterAura]) -> bool {
    auras.len() <= usize::from(CHARACTER_AURA_SLOTS)
        && auras.iter().all(|aura| {
            aura.slot < CHARACTER_AURA_SLOTS
                && aura.spell_id != 0
                && aura.flags <= 0x0f
                && aura.flags & 0x0e != 0
                && aura.stacks != 0
                && aura.remaining_ms != Some(0)
        })
        && auras.iter().enumerate().all(|(index, aura)| {
            !auras[index + 1..]
                .iter()
                .any(|other| other.slot == aura.slot)
        })
}

