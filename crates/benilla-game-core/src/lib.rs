    /// Extend the converted population around `position` on its map, returning the source spawn
    /// ids added. Spawns stream in only (project decision): a creature already in `hostiles` or
    /// `allies` is left alone, and nothing is ever removed. `enter_world` seeds with it and the
    /// adapter repeats it as the player travels, so simulation and presentation agree on the set.
    /// Each template's converted [`UnitReactions`] row decides the hostile/friendly split and
    /// whether the creature is aggressive.
    pub fn populate_near(&mut self, position: WorldPosition, radius_yards: f32) -> Vec<u32> {
        let content = content::creature_content();
        let mut added = Vec::new();
        for spawn in content.spawns_near(position.map_id, position.x, position.y, radius_yards) {
            if self
                .hostiles
                .iter()
                .any(|hostile| hostile.spawn_id == spawn.source_guid)
                || self
                    .allies
                    .iter()
                    .any(|ally| ally.spawn_id == spawn.source_guid)
            {
                continue;
            }
            let Some(template) = content.template(spawn.entry) else {
                continue;
            };
            let spawn_position = WorldPosition {
                map_id: spawn.map_id,
                x: spawn.x,
                y: spawn.y,
                z: spawn.z,
                orientation: spawn.orientation,
            };
            match self.unit_reactions.reaction(template.faction) {
                UnitReaction::Friendly => {
                    // Friendly templates share the unit presentation and receive friendly spells;
                    // they never enter combat.
                    self.allies.push(AllyState {
                        spawn_id: spawn.source_guid,
                        creature_entry: spawn.entry,
                        position: spawn_position,
                        health: FRIENDLY_MAX_HEALTH,
                        max_health: FRIENDLY_MAX_HEALTH,
                        auras: Vec::new(),
                    });
                }
                reaction => {
                    self.hostiles.push(hostile_from_spawn(
                        spawn.source_guid,
                        spawn.entry,
                        spawn_position,
                        reaction == UnitReaction::Hostile,
                    ));
                }
            }
            added.push(spawn.source_guid);
        }
        added
    }

    pub fn open_corpse_loot(&mut self, spawn_id: u32) -> Result<loot::LootWindow, loot::LootError> {
        let id = self
            .active
            .as_ref()
            .ok_or(loot::LootError::NoActiveCharacter)?;
        let hostile = self
            .hostile(spawn_id)
            .filter(|hostile| hostile.health == 0 && hostile.respawn_remaining_ms.is_some())
            .ok_or(loot::LootError::NotLootable)?;
        let corpse = self
            .snapshots
            .get(id)
            .and_then(|snapshot| {
                snapshot
                    .corpse_loot
                    .iter()
                    .find(|corpse| corpse.spawn_id == hostile.spawn_id)
            })
            .ok_or(loot::LootError::NotLootable)?;
        self.open_loot_spawn_id = Some(spawn_id);
        Ok(loot::LootWindow {
            gold: if corpse.money_looted {
                0
            } else {
                corpse.loot.gold
            },
            items: corpse
                .loot
                .items
                .iter()
                .enumerate()
                .filter(|(slot, _)| !corpse.looted_items[*slot])
                .map(|(slot, item)| (slot as u8, item.clone()))
                .collect(),
        })
    }

    pub fn take_corpse_loot(&mut self, slot: u8) -> Result<quest::InventoryItem, loot::LootError> {
        let id = self
            .active
            .as_ref()
            .cloned()
            .ok_or(loot::LootError::NoActiveCharacter)?;
        let spawn_id = self
            .open_loot_spawn_id
            .ok_or(loot::LootError::NotLootable)?;
        let snapshot = self
            .snapshots
            .get_mut(&id)
            .ok_or(loot::LootError::NoActiveCharacter)?;
        let corpse_index = snapshot
            .corpse_loot
            .iter()
            .position(|corpse| corpse.spawn_id == spawn_id)
            .ok_or(loot::LootError::NotLootable)?;
        let index = usize::from(slot);
        let corpse = &snapshot.corpse_loot[corpse_index];
        let item = corpse
            .loot
            .items
            .get(index)
            .filter(|_| !corpse.looted_items.get(index).copied().unwrap_or(true))
            .ok_or(loot::LootError::InvalidSlot)?
            .clone();
        let backpack_slot = (0..quest::BACKPACK_SLOTS)
            .find(|slot| {
                !snapshot
                    .inventory
                    .iter()
                    .any(|existing| existing.slot == *slot)
            })
            .ok_or(loot::LootError::BackpackFull)?;
        let instance_id = next_instance_id(snapshot).ok_or(loot::LootError::BackpackFull)?;
        let item = quest::InventoryItem {
            instance_id,
            entry: item.entry,
            count: item.count,
            slot: backpack_slot,
        };
        snapshot.inventory.push(item);
        snapshot.inventory.sort_by_key(|item| item.slot);
        snapshot.corpse_loot[corpse_index].looted_items[index] = true;
        Ok(item)
    }

    pub fn take_corpse_money(&mut self) -> Result<u32, loot::LootError> {
        let id = self
            .active
            .as_ref()
            .cloned()
            .ok_or(loot::LootError::NoActiveCharacter)?;
        let spawn_id = self
            .open_loot_spawn_id
            .ok_or(loot::LootError::NotLootable)?;
        let snapshot = self
            .snapshots
            .get_mut(&id)
            .ok_or(loot::LootError::NoActiveCharacter)?;
        let corpse = snapshot
            .corpse_loot
            .iter_mut()
            .find(|corpse| corpse.spawn_id == spawn_id)
            .ok_or(loot::LootError::NotLootable)?;
        if corpse.money_looted {
            return Ok(0);
        }
        let total = snapshot
            .money_copper
            .checked_add(corpse.loot.gold)
            .ok_or(loot::LootError::MoneyOverflow)?;
        let amount = corpse.loot.gold;
        snapshot.money_copper = total;
        corpse.money_looted = true;
        Ok(amount)
    }

