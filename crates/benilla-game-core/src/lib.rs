    #[test]
    fn checksum_corruption_and_unknown_schema_are_reported() {
        let (core, id, _) = core_with_two();
        let encoded = core.encode_snapshot(&id).unwrap();
        let corrupted = encoded.replace("Alara", "Alira");
        assert_eq!(
            decode_snapshot(&corrupted),
            Err(SaveError::ChecksumMismatch)
        );

        let current_version = format!("schema_version = {SNAPSHOT_VERSION}");
        let unsupported = encoded.replace(&current_version, "schema_version = 99");
        assert_eq!(
            decode_snapshot(&unsupported),
            Err(SaveError::UnsupportedVersion(99))
        );

        let downgraded = encoded.replacen(&current_version, "schema_version = 2", 1);
        assert!(matches!(
            decode_snapshot(&downgraded),
            Err(SaveError::InvalidToml(_))
        ));
    }

