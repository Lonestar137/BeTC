    pub fn corpse_has_loot(&self, spawn_id: u32) -> bool {
        self.active
            .as_ref()
            .and_then(|id| self.snapshots.get(id))
            .and_then(|snapshot| {
                snapshot
                    .corpse_loot
                    .iter()
                    .find(|corpse| corpse.spawn_id == spawn_id)
            })
            .is_some_and(|corpse| {
                (!corpse.money_looted && corpse.loot.gold > 0)
                    || corpse
                        .loot
                        .items
                        .iter()
                        .zip(&corpse.looted_items)
                        .any(|(_, looted)| !looted)
            })
    }

