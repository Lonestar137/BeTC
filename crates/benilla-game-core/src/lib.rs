    /// Add or refresh a slot, preserving cache order for a refresh and appending a replacement.
    pub fn set_active_aura(&mut self, aura: CharacterAura) -> Result<(), CoreError> {
        if !valid_auras(std::slice::from_ref(&aura)) {
            return Err(CoreError::InvalidAura);
        }
        let id = self.active.as_ref().ok_or(CoreError::NoCharacterSelected)?;
        let snapshot = self
            .snapshots
            .get_mut(id)
            .ok_or(CoreError::CharacterNotFound)?;
        if let Some(index) = snapshot
            .auras
            .iter()
            .position(|existing| existing.slot == aura.slot)
        {
            if snapshot.auras[index].spell_id == aura.spell_id {
                snapshot.auras[index] = aura;
            } else {
                snapshot.auras.remove(index);
                snapshot.auras.push(aura);
            }
        } else if snapshot.auras.len() < usize::from(CHARACTER_AURA_SLOTS) {
            snapshot.auras.push(aura);
        } else {
            return Err(CoreError::InvalidAura);
        }
        Ok(())
    }

    pub fn remove_active_aura(&mut self, slot: u8) -> Option<CharacterAura> {
        let id = self.active.as_ref()?;
        let snapshot = self.snapshots.get_mut(id)?;
        let index = snapshot.auras.iter().position(|aura| aura.slot == slot)?;
        Some(snapshot.auras.remove(index))
    }

    /// Count down finite aura durations on game time and return the slots that expired.
    pub fn advance_active_auras(&mut self, elapsed_ms: u32) -> Vec<CharacterAura> {
        let Some(id) = self.active.as_ref() else {
            return Vec::new();
        };
        let Some(snapshot) = self.snapshots.get_mut(id) else {
            return Vec::new();
        };
        let mut expired = Vec::new();
        for aura in &mut snapshot.auras {
            if let Some(remaining_ms) = aura.remaining_ms {
                if elapsed_ms >= remaining_ms {
                    expired.push(*aura);
                } else {
                    aura.remaining_ms = Some(remaining_ms - elapsed_ms);
                }
            }
        }
        snapshot
            .auras
            .retain(|aura| !expired.iter().any(|expired| expired.slot == aura.slot));
        expired
    }

    /// Keep simulation combat positions aligned with presentation-only patrol movement.
    pub fn update_hostile_position(
        &mut self,
        spawn_id: u32,
        position: WorldPosition,
        spline_id: u32,
    ) -> bool {
        let Some(hostile) = self
            .hostiles
            .iter_mut()
            .find(|hostile| hostile.spawn_id == spawn_id)
        else {
            return false;
        };
        if !position.is_finite()
            || position.map_id != hostile.position.map_id
            || hostile.engaged
            || hostile.provoked
            || hostile.evading
        {
            return false;
        }
        hostile.position = position;
        hostile.spline_id = spline_id;
        true
    }

