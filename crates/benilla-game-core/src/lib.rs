impl fmt::Display for CoreError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Self::InvalidCharacterId => "character ID must be 32 hexadecimal characters",
            Self::InvalidName => "name must contain 2 to 12 letters",
            Self::DuplicateName => "a character with that name already exists",
            Self::RosterFull => "the local roster is full",
            Self::CharacterNotFound => "character does not exist",
            Self::CharacterActive => "leave the world before deleting the active character",
            Self::NoCharacterSelected => "select a character before entering the world",
            Self::InvalidPosition => "position coordinates and orientation must be finite",
            Self::InvalidAppearance => "character proportions are outside their supported range",
            Self::UnknownAbility => "the character does not know that ability",
            Self::InvalidTarget => "the target is not a living attackable creature",
            Self::OutOfRange => "the target is out of range",
            Self::CastInProgress => "another ability is already being cast",
            Self::AbilityOnCooldown => "the ability is on cooldown",
            Self::InsufficientPower => "not enough mana",
            Self::CharacterDead => "a dead character cannot start combat",
            Self::CharacterAlive => "the active character is not dead",
            Self::InvalidAura => "aura slot or aura state is invalid",
            Self::UnsupportedSpellEffect => {
                "the spell effect is not supported by the offline simulation"
            }
            Self::UnknownItem => "no item is in that inventory slot",
            Self::ItemNotEquippable => "the item cannot be equipped",
            Self::WrongEquipSlot => "the item does not fit that equipment slot",
            Self::BackpackFull => "the backpack has no free slot",
        })
    }
}

